"""Generate web/ds/kds.css from the Kolesa design system (design/kolesa-ds/: tokens.json + bundle.css,
copied from https://claude.ai/artifact/7CtkB2B4Ma1KqD6GkQBkRa). Re-run after updating those copies."""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = root / 'design' / 'kolesa-ds'
t = json.loads((src / 'tokens.json').read_text(encoding='utf-8'))
toks = {x['name']: x['value'] for x in t['color']['tokens']}
themes = [th['id'] for th in t['color']['themes']]
def val(name, theme, depth=0):
    v = toks[name]
    if isinstance(v, dict): v = v.get(theme, v.get(themes[0]))
    m = re.fullmatch(r'\{(.+)\}', v)
    return val(m.group(1), theme, depth + 1) if m and depth < 10 else v
def block(theme):
    lines = [f'  --{n}: {val(n, theme)};' for n in toks]
    if theme == themes[0]:
        for fam in ('spacing', 'radius', 'size'):
            lines += [f"  --{x['name'].replace('.', '_')}: {x['value']};" for x in t.get(fam, {}).get('tokens', [])]
        lines += [f"  --font-{k}: {v};" for k, v in t['type']['families'].items()]
    return '\n'.join(lines)
css = (src / 'bundle.css').read_text(encoding='utf-8')
# keep base, controls and gradients; take only the motion tokens (durations, eases) from the motion part
head = css[:css.index('/* ── Motion')]
head = re.sub(r'/\* Preview helpers \*/.*?(?=/\* ──)', '', head, flags=re.S)
mot = re.search(r'/\* ── Motion.*?(:root \{.*?\})', css, flags=re.S).group(1)
out = ['/* Kolesa design system — generated by tools/build_ds.py from design/kolesa-ds/ */',
       ':root {\n' + block('light') + '\n}',
       ':is([data-theme="dark"], .dark) {\n' + block('dark') + '\n}',
       head.replace('@import url', '/* fonts: <link> in index.html */ /* @import url').replace('display=swap");', 'display=swap"); */', 1),
       mot]
(root / 'web' / 'ds').mkdir(exist_ok=True)
(root / 'web' / 'ds' / 'kds.css').write_text('\n\n'.join(out), encoding='utf-8')
print('ok')
